"""Builds data.js for the Watershed case graphics from the case pages (../*.md).

Run from this folder:  python3 build-data.py
Re-run whenever a case page changes. Items marked [verify] in a case page are
carried with verify: true and stay hidden until the marker is removed there.
"""
import json, re, pathlib

HERE = pathlib.Path(__file__).resolve().parent
CASES = {
    "01": "01-evidence-into-practice.md",
    "02": "02-access-without-asking.md",
    "03": "03-the-people-who-carry-care.md",
    "04": "04-knowing-whether-it-worked.md",
    "05": "05-learning-through-ai.md",
}
SUP = str.maketrans("⁰¹²³⁴⁵⁶⁷⁸⁹", "0123456789")
VERIFY = re.compile(r"\s*\*\*\[verify[^\]]*\]\*\*|\s*\[verify[^\]]*\]")


def clean(text):
    """Return (text with citations as {n}, verify flag)."""
    verify = bool(VERIFY.search(text))
    text = VERIFY.sub("", text).strip()
    text = re.sub(r"\*([^*]+)\*", r"\1", text)          # drop markdown italics
    text = re.sub(r"\*\*([^*]+)\*\*", r"\1", text)      # drop markdown bold
    # citation runs like ⁶ ⁷ ⁸ or ¹⁰ → {6,7,8} / {10}
    def cite(m):
        nums = [n.translate(SUP) for n in m.group(0).split()]
        return "{" + ",".join(nums) + "}"
    text = re.sub(r"[⁰¹²³⁴⁵⁶⁷⁸⁹]+(?:\s[⁰¹²³⁴⁵⁶⁷⁸⁹]+)*", cite, text)
    return text.strip(), verify


def section(md, title):
    m = re.search(r"^## " + re.escape(title) + r".*?$(.*?)(?=^## |\Z)", md, re.S | re.M)
    return m.group(1) if m else ""


def table_rows(block):
    rows = [l for l in block.splitlines() if l.startswith("|")][2:]
    return [[c.strip() for c in r.strip("|").split("|")] for r in rows]


def build(md):
    head = md.splitlines()
    title = next(l[2:] for l in head if l.startswith("# "))
    eyebrow = head[0].strip()
    question = next(l for l in head[head.index("# " + title) + 1:] if l.strip())

    # three questions
    tq = section(md, "The three questions")
    questions = []
    for name in ("Scale", "Neglectedness", "Solvability"):
        m = re.search(r"^(?:\*\*)?" + name + r"(?:\*\*)?\n(.*?)\n\*?What could be:\*?\s*(.*?)\n", tq, re.S | re.M)
        items = []
        for line in m.group(1).splitlines():
            if line.startswith("- "):
                t, v = clean(line[2:])
                items.append({"text": t, "verify": v})
        could, v = clean(m.group(2))
        questions.append({"name": name, "findings": items, "could": could, "couldVerify": v})

    # reading the figures
    figures = []
    for fig, measures, notshow in table_rows(section(md, "Reading the figures")):
        f1, v1 = clean(fig.strip('"').replace('"', "")); m1, v2 = clean(measures); n1, v3 = clean(notshow)
        figures.append({"figure": f1, "measures": m1, "notShow": n1, "verify": v1 or v2 or v3})

    # theory of change
    toc = section(md, "Theory of change")
    links = []
    for m in re.finditer(r"^\d\. (?:\*\*)?(\w+):(?:\*\*)? (.*?) \*?Assumes (.*?)\*?()$", toc, re.M):
        stage = m.group(1)
        what, _ = clean(m.group(2))
        assumes, v = clean("Assumes " + m.group(3) + m.group(4))
        links.append({"stage": stage, "what": what, "assumes": assumes, "verify": v})
    wm = re.search(r"^The weakest link is (\d) to (\d): (.*)$", toc, re.M)
    wtext, wv = clean(wm.group(3))
    weakest = {"from": int(wm.group(1)), "to": int(wm.group(2)), "text": wtext, "verify": wv}

    # effort
    effort = []
    for less, more in table_rows(section(md, "Where effort counts for less, and for more")):
        l, v1 = clean(less); mo, v2 = clean(more)
        effort.append({"less": l, "more": mo, "verify": v1 or v2})

    return {"eyebrow": eyebrow, "title": title, "question": question, "questions": questions,
            "figures": figures, "links": links, "weakest": weakest, "effort": effort}


data = {k: build((HERE.parent / f).read_text(encoding="utf-8")) for k, f in CASES.items()}
out = ("/* Generated by build-data.py from the case pages. Edit the case pages, then re-run.\n"
       "   Items with verify: true stay hidden until their [verify] marker is removed. */\n"
       "window.WATERSHED_CASES = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n")
(HERE / "data.js").write_text(out, encoding="utf-8")
print("wrote data.js:", {k: (len(v["figures"]), len(v["links"]), len(v["effort"])) for k, v in data.items()})
